/**
 * Builds m2/contracts/REVIEW.md: every staging recording (m2/contracts/recorded) compared with its approved
 * baseline (m2/contracts/approved) — new cases, changed status, changed keys/types, new or missing PII keys — with
 * the same rules the tests use (baseline.ts: list-item data differences ignored, a NEW PII key always reported).
 * Value-free: recordings hold only statuses, shapes and PII key NAMES.
 *
 *   npm run m2:contracts:review
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  approvedFile,
  CONTRACTS_DIR,
  invalidAcceptedProblem,
  isInvalidVariant,
  piiKeyDiff,
  shapeDiff,
  type BaselineFile,
} from '../src/baseline/baseline';

const recordedDir = path.join(CONTRACTS_DIR, 'recorded');
const files = existsSync(recordedDir) ? readdirSync(recordedDir).filter((f) => f.endsWith('.json')) : [];
const rows: string[] = [];
let changed = 0;
for (const f of files.sort()) {
  const rec = JSON.parse(readFileSync(path.join(recordedDir, f), 'utf8')) as BaselineFile;
  const app = existsSync(approvedFile(rec.caseId))
    ? (JSON.parse(readFileSync(approvedFile(rec.caseId), 'utf8')) as BaselineFile)
    : undefined;
  for (const [label, obs] of Object.entries(rec.variants)) {
    const want = app?.variants[label];
    const pii = want ? piiKeyDiff(want, obs) : { failures: [], notes: [] };
    const notes = !want
      ? ['new — not approved yet']
      : [
          ...(want.status !== obs.status ? [`status ${want.status} → ${obs.status}`] : []),
          ...shapeDiff(want.shape, obs.shape),
          ...pii.failures,
        ];
    if (rec.invariantFailures?.includes(label) || obs.status >= 500)
      notes.unshift('BROKE AN INVARIANT while recording (see the test failure) — never approved');
    // Audit fix 2026-10-25: a 2xx to invalid input fails unless acceptedBecause names the code reference.
    if (invalidAcceptedProblem(rec.caseId, label, obs.status, app))
      notes.push(
        'INVALID INPUT ACCEPTED (2xx) — fails until a code reference is recorded with --accept "<label>=<code ref>", otherwise a finding',
      );
    const accepted =
      isInvalidVariant(rec.caseId, label) && app?.acceptedBecause?.[label] && obs.status < 300
        ? `; 2xx accepted: ${app.acceptedBecause[label]}`
        : '';
    if (notes.length) changed++;
    const ok = pii.notes.length
      ? `matches approved (list-item data differences ignored; ${pii.notes.join('; ')})${accepted}`
      : `matches approved (list-item data differences ignored)${accepted}`;
    rows.push(
      `| ${rec.caseId} | ${label} | ${obs.status} | ${obs.piiKeys.join(', ') || '—'} | ${notes.join('; ') || ok} |`,
    );
  }
  if (app?.reRecord)
    rows.push(
      `| ${rec.caseId} | (all) | — | — | APPROVED FILE MARKED FOR RE-RECORDING — ${app.reRecord}; approving replaces it |`,
    );
  // Variants deliberately not sent (safety rule, M2Q-46): listed so the review sees them, never approved.
  for (const [label, reason] of Object.entries(rec.notSent ?? {}))
    rows.push(`| ${rec.caseId} | ${label} | — | — | NOT SENT — ${reason}; never approved |`);
}
const md = [
  '# M2 contract recordings — review',
  '',
  'Generated by `npm run m2:contracts:review` from `m2/contracts/recorded/` (recorded only on explicit request with',
  '`npm run m2:contracts:record`). Approve a reviewed case with `npm run m2:contracts:approve -- --by "<name>" <case…|all>`;',
  'tests assert only against `m2/contracts/approved/`. Staging already runs the PII branch: baselines catch future',
  'changes, not differences from master (M2Q-24 answer). Recordings hold statuses, key/type shapes and PII key names only.',
  '',
  `${files.length} recorded case(s), ${changed} variant(s) new or changed.`,
  '',
  '| Case | Variant | Status | PII keys | Review |',
  '| --- | --- | --- | --- | --- |',
  ...rows,
  '',
].join('\n');
writeFileSync(path.join(CONTRACTS_DIR, 'REVIEW.md'), md);
console.log(
  `m2/contracts/REVIEW.md — ${files.length} recorded case(s), ${changed} new or changed variant(s)`,
);
